        html.append("</style>\n</head>\n<body>\n");

        // Slide 1: Cover
        html.append("<div class=\"slide\">\n");
        html.append("  <div class=\"slide-header\">Slide 1 of 10 &bull; Executive Summary</div>\n");
        html.append("  <h1>").append(idea.getStartupName()).append("</h1>\n");
        html.append("  <p style=\"font-size: 18px; color: #94A3B8;\">Target Market: ").append(idea.getTargetCustomer()).append("</p>\n");
        html.append("  <span class=\"badge badge-go\">Decision Intelligence: ").append(idea.getDecisionTier().getLabel()).append(" (Score: ").append(idea.getOverallScore()).append("/100)</span>\n");
        html.append("  <p>Engineered using VentureLens Startup Operating System &bull; ").append(dateStr).append("</p>\n");
        html.append("</div>\n");

        // Slide 2: Problem
        html.append("<div class=\"slide\">\n");
