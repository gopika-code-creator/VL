        for (String o : idea.getOpportunities()) html.append("<li>").append(o).append("</li>");
        html.append("</ul></div>\n");

        html.append("    <div class=\"swot-box\"><div class=\"swot-title\" style=\"color:#F59E0B;\">Threats</div><ul>");
        for (String t : idea.getThreats()) html.append("<li>").append(t).append("</li>");
        html.append("</ul></div>\n");

        html.append("  </div>\n");
        html.append("</div>\n");

