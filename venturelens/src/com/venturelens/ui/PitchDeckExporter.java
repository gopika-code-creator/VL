        html.append("  @media print {\n");
        html.append("    body { background: white !important; color: black !important; padding: 0 !important; }\n");
        html.append("    .slide { background: white !important; color: black !important; border: 1px solid #ccc !important; page-break-after: always; margin-bottom: 0 !important; border-radius: 0 !important; box-shadow: none !important; }\n");
