            html.append("    <div class=\"stat-card\"><div class=\"stat-label\">Survival Runway</div><div class=\"stat-value\">").append(String.format("%.1f", ledger.getRunwayMonths())).append(" Months</div></div>\n");
            html.append("    <div class=\"stat-card\"><div class=\"stat-label\">Zero-Cash Date</div><div class=\"stat-value\">").append(ledger.getZeroCashDateEstimate()).append("</div></div>\n");
