        html.append("</div>\n");

        // Slide 4: SWOT
        html.append("<div class=\"slide\">\n");
        html.append("  <div class=\"slide-header\">Slide 4 of 10 &bull; Strategic SWOT Analysis</div>\n");
        html.append("  <h2>System-Evaluated SWOT Matrix</h2>\n");
        html.append("  <div class=\"grid-4\">\n");

        html.append("    <div class=\"swot-box\"><div class=\"swot-title\">Strengths</div><ul>");
        for (String s : idea.getStrengths()) html.append("<li>").append(s).append("</li>");
        html.append("</ul></div>\n");

        html.append("    <div class=\"swot-box\"><div class=\"swot-title\" style=\"color:#EF4444;\">Weaknesses</div><ul>");
        for (String w : idea.getWeaknesses()) html.append("<li>").append(w).append("</li>");
